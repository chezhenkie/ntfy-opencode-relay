// Writes the IANA TLD table in rust/crates/core/src/tlds.rs from tlds.txt.
//
// usage: node tools\link-safety\build-tlds.mjs [--check]
//   --check  report drift without writing, exit 1 when out of date

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const source = path.join(here, "tlds.txt");
const rustTable = path.join(root, "rust", "crates", "core", "src", "tlds.rs");
const checkOnly = process.argv.includes("--check");

const lines = readFileSync(source, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line.length > 0 && !line.startsWith("#"));
// punycode TLDs are dropped on purpose: the filter matches ASCII tokens only.
const valid = lines.filter((line) => /^[a-z]{2,24}$/.test(line));
const skipped = lines.length - valid.length;
if (valid.length === 0) {
    throw new Error("no valid TLD entries");
}
const unique = [...new Set(valid)];
if (unique.length !== valid.length) {
    throw new Error(`duplicate TLD entries: ${valid.length - unique.length}`);
}

const rows = [];
for (let index = 0; index < unique.length; index += 8) {
    rows.push(`    ${unique.slice(index, index + 8).map((tld) => `"${tld}"`).join(", ")},`);
}
const rustText = [
    "//! Generated by `node tools/link-safety/build-tlds.mjs` from",
    "//! `tools/link-safety/tlds.txt`. Do not edit by hand.",
    "",
    "/// IANA top-level domains, lowercase, sorted; punycode omitted.",
    "#[rustfmt::skip]",
    `pub static IANA_TLDS: [&str; ${unique.length}] = [`,
    ...rows,
    "];",
    "",
    "/// Membership in the sorted IANA table.",
    "pub fn is_iana_tld(tld: &str) -> bool {",
    "    IANA_TLDS.binary_search(&tld).is_ok()",
    "}",
    "",
].join("\n");
const normalize = (value) => value.replace(/\r\n/g, "\n");

const rustCurrent = existsSync(rustTable) ? readFileSync(rustTable, "utf8") : "";
const rustDrift = normalize(rustCurrent) !== rustText;

if (checkOnly) {
    if (rustDrift) {
        console.error(`FAIL tlds=${unique.length} rustDrift=true`);
        process.exit(1);
    }
    console.log(`PASS tlds=${unique.length} rust table current`);
    process.exit(0);
}

if (rustDrift) {
    writeFileSync(rustTable, rustText);
}

console.log(`tlds=${unique.length} skipped=${skipped} rustSynced=${rustDrift}`);
